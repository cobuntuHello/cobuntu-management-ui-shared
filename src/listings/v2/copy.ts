export type ListingPageCopyKey = keyof typeof LISTING_PAGE_COPY;
export type ListingPageCopy = Partial<Record<ListingPageCopyKey, string>>;

/** Fill `{name}` placeholders; an unknown placeholder stays visible rather than vanishing. */
export function fill(text: string, vars?: Record<string, unknown>): string {
    if (!vars) return text;
    return text.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined || vars[k] === null ? m : String(vars[k])));
}

/**
 * The page's translator: the host's override, then the host's `t`, then English.
 * A `t` that answers with the key itself (next-intl's miss) falls through.
 */
export function makeSay(copy?: ListingPageCopy, t?: (key: string, vars?: Record<string, unknown>) => string) {
    return (key: ListingPageCopyKey, vars?: Record<string, unknown>): string => {
        const own = copy?.[key];
        if (own) return fill(own, vars);
        if (t) {
            try {
                const out = t(key, vars);
                if (out && out !== key && !out.endsWith(`.${key}`)) return out;
            } catch { /* missing in the host's messages: English below */ }
        }
        return fill(LISTING_PAGE_COPY[key], vars);
    };
}

export type Say = ReturnType<typeof makeSay>;
